package monitor

import (
	"context"
	"errors"
	"slices"
	"sort"
	"time"
)

type LiveClient struct {
	ID        string   `json:"id"`
	Email     string   `json:"email"`
	Inbounds  []int    `json:"inbound_ids"`
	Status    string   `json:"status"`
	RateState string   `json:"rate_state"`
	Up        *int64   `json:"up"`
	Down      *int64   `json:"down"`
	UpRate    *float64 `json:"up_per_second"`
	DownRate  *float64 `json:"down_per_second"`
}

type LiveSnapshot struct {
	UpdatedAt       string       `json:"updated_at"`
	SampleSeconds   float64      `json:"sample_seconds"`
	IntervalSeconds int          `json:"interval_seconds"`
	OnlineAvailable bool         `json:"online_available"`
	Stale           bool         `json:"stale"`
	Items           []LiveClient `json:"items"`
}

func (c *Collector) fetchOnline(ctx context.Context) ([]string, error) {
	var envelope struct {
		Success bool     `json:"success"`
		Obj     []string `json:"obj"`
	}
	// The official read-only online-list route uses POST with no request body.
	if err := c.readAPI(ctx, "clients/onlines", &envelope); err != nil || !envelope.Success {
		return nil, errors.New("online status unavailable")
	}
	return envelope.Obj, nil
}

func (c *Collector) updateRealtime(at time.Time, snaps []Snapshot, online []string, onlineAvailable bool) {
	c.mu.Lock()
	defer c.mu.Unlock()
	previous, _ := time.Parse(time.RFC3339Nano, c.live.UpdatedAt)
	elapsed := at.Sub(previous).Seconds()
	if previous.IsZero() || elapsed <= 0 {
		elapsed = 0
	}
	next := LiveSnapshot{UpdatedAt: stamp(at), SampleSeconds: elapsed, IntervalSeconds: int(c.cfg.Interval().Seconds()), OnlineAvailable: onlineAvailable, Items: []LiveClient{}}
	onlineSet := map[string]bool{}
	for _, email := range online {
		onlineSet[email] = true
	}
	baselines := make(map[string]Snapshot, len(snaps))
	for _, sample := range snaps {
		row := LiveClient{ID: sample.ID, Email: sample.Email, Inbounds: sample.InboundIDs, Status: "unknown", RateState: "baseline"}
		if onlineAvailable {
			row.Status = "offline"
			if onlineSet[sample.Email] {
				row.Status = "online"
			}
		}
		if old, ok := c.liveBaselines[sample.ID]; ok && old.HasTraffic && sample.HasTraffic && elapsed > 0 {
			switch {
			case sample.Up < old.Up || sample.Down < old.Down:
				row.RateState = "reset"
			case elapsed > 3*c.cfg.Interval().Seconds():
				row.RateState = "gap"
			default:
				up, down := sample.Up-old.Up, sample.Down-old.Down
				upRate, downRate := float64(up)/elapsed, float64(down)/elapsed
				row.Up, row.Down, row.UpRate, row.DownRate = &up, &down, &upRate, &downRate
				row.RateState = "ok"
			}
		}
		baselines[sample.ID] = sample
		next.Items = append(next.Items, row)
	}
	sort.Slice(next.Items, func(i, j int) bool { return next.Items[i].Email < next.Items[j].Email })
	c.live, c.liveBaselines = next, baselines
}

func (c *Collector) realtimeUnavailable() {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.live.Stale = true
	c.liveBaselines = nil
}

func (c *Collector) invalidateLiveBaselines(clients []resetClient) {
	c.mu.Lock()
	defer c.mu.Unlock()
	for _, client := range clients {
		delete(c.liveBaselines, client.ID)
		for i := range c.live.Items {
			if c.live.Items[i].ID == client.ID {
				row := &c.live.Items[i]
				row.Up, row.Down, row.UpRate, row.DownRate = nil, nil, nil, nil
				row.RateState = "reset"
			}
		}
	}
}

// Browser polls read an in-memory snapshot. No extra per-visit rows or queries
// to Xray/3x-ui are generated by viewing this endpoint.
func (c *Collector) Realtime(now time.Time, clientID string, inboundID int) LiveSnapshot {
	c.mu.RLock()
	defer c.mu.RUnlock()
	out := c.live
	out.Items = []LiveClient{}
	out.IntervalSeconds = int(c.cfg.Interval().Seconds())
	at, err := time.Parse(time.RFC3339Nano, out.UpdatedAt)
	out.Stale = out.Stale || err != nil || now.Sub(at) > c.cfg.Interval()*3
	if out.Stale {
		out.OnlineAvailable = false
	}
	for _, item := range c.live.Items {
		if (clientID != "" && item.ID != clientID) || (inboundID != 0 && !slices.Contains(item.Inbounds, inboundID)) {
			continue
		}
		if out.Stale {
			item.Status, item.RateState = "unknown", "stale"
			item.Up, item.Down, item.UpRate, item.DownRate = nil, nil, nil, nil
		}
		out.Items = append(out.Items, item)
	}
	return out
}
